#!/usr/bin/env python3
"""Reproduce Perth's native weights and Android's non-pickle, pinned ZIP recipe.

Only accepts the official checkpoint at the recorded revision. Android copies exact
F32 tensor storages from the ZIP; it never interprets data.pkl or runs Python.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import struct
import zipfile
from pathlib import Path

REVISION = "ff1c8ac55a976971245cdd53c18d6131ca00d993"
SOURCE_PATH = "src/perth/perth_net/pretrained/implicit/perth_net_250000.pth.tar"
SOURCE_BYTES = 37429684
SOURCE_SHA256 = "a15bce457ebc53ce5e6c9c3f11df78cf7ee2bf9cdab0a798902135b4c4027670"
SOURCE_URL = f"https://raw.githubusercontent.com/resemble-ai/Perth/{REVISION}/{SOURCE_PATH}"


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("checkpoint", type=Path)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--recipe", type=Path, required=True)
    parser.add_argument("--kotlin", type=Path, required=True)
    args = parser.parse_args()
    raw = args.checkpoint.read_bytes()
    if len(raw) != SOURCE_BYTES or sha(raw) != SOURCE_SHA256:
        raise SystemExit("The official Perth checkpoint size/SHA-256 does not match the pinned revision")
    import torch
    state = torch.load(args.checkpoint, map_location="cpu", weights_only=True)["model"]
    groups = ["encoder.layers", "decoder.slow_layers", "decoder.normal_layers", "decoder.fast_layers"]
    inventory = []
    storages = {}
    with zipfile.ZipFile(args.checkpoint) as archive:
        for entry in archive.infolist():
            if entry.compress_type != zipfile.ZIP_STORED or entry.is_dir():
                raise SystemExit("Expected the exact uncompressed official checkpoint ZIP")
            inventory.append({"name": entry.filename, "bytes": entry.file_size})
            if "/data/" in entry.filename:
                data = archive.read(entry)
                storages.setdefault((len(data), sha(data)), entry.filename)
    binary = bytearray(b"CBPERTH1" + struct.pack("<6if", 2, 32000, 2048, 320, 2048, 128, 1e-9))
    layers = []
    for group in groups:
        binary += struct.pack("<i", 7)
        branch = []
        for index in range(7):
            prefix = f"{group}.{index}.conv"
            weight, bias = [state[f"{prefix}.{kind}"].detach().cpu().contiguous() for kind in ("weight", "bias")]
            if weight.dtype != torch.float32 or bias.dtype != torch.float32:
                raise SystemExit("Expected exact F32 tensor storage")
            out_channels, in_channels, kernel = weight.shape
            if tuple(bias.shape) != (out_channels,):
                raise SystemExit("Invalid bias shape")
            activation = int(index != 6)
            binary += struct.pack("<4i", out_channels, in_channels, kernel, activation)
            tensors = []
            for tensor in (weight, bias):
                data = tensor.numpy().astype("<f4", copy=False).tobytes(order="C")
                storage = storages.get((len(data), sha(data)))
                if storage is None:
                    raise SystemExit(f"Tensor {prefix} is not an exact standalone F32 ZIP storage")
                tensors.append({"name": storage, "bytes": len(data), "sha256": sha(data)})
                binary += data
            branch.append({"outChannels": out_channels, "inChannels": in_channels, "kernel": kernel,
                           "activation": activation, "weight": tensors[0], "bias": tensors[1]})
        layers.append(branch)
    recipe = {"revision": REVISION, "sourceUrl": SOURCE_URL, "sourceBytes": SOURCE_BYTES,
              "sourceSha256": SOURCE_SHA256, "outputBytes": len(binary), "outputSha256": sha(binary),
              "zipEntries": inventory, "groups": layers}
    for path in (args.output, args.recipe, args.kotlin):
        path.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_bytes(binary)
    args.recipe.write_text(json.dumps(recipe, ensure_ascii=False, indent=2) + "\n")
    lines = ["// Generated by scripts/voice/export-perth.py from the pinned official checkpoint.",
             "package com.sal7one.hearth.tts.chatterbox", "", "internal object ChatterboxPerthRecipe {",
             f"    const val SOURCE_URL = {json.dumps(SOURCE_URL)}",
             f"    const val SOURCE_BYTES = {SOURCE_BYTES}L",
             f"    const val SOURCE_SHA256 = {json.dumps(SOURCE_SHA256)}",
             f"    const val OUTPUT_BYTES = {len(binary)}L",
             f"    const val OUTPUT_SHA256 = {json.dumps(sha(binary))}",
             "    val value = PerthRecipe(SOURCE_BYTES, SOURCE_SHA256, OUTPUT_BYTES, OUTPUT_SHA256,",
             "        entries = mapOf("]
    lines += [f'            "{entry["name"]}" to {entry["bytes"]}L,' for entry in inventory]
    lines += ["        ), groups = listOf("]
    for branch in layers:
        lines.append("            listOf(")
        for layer in branch:
            def tensor_code(value):
                return f'PerthTensor("{value["name"]}", {value["bytes"]}L, "{value["sha256"]}")'
            lines += [f'                PerthLayer({layer["outChannels"]}, {layer["inChannels"]}, {layer["kernel"]}, {layer["activation"]},',
                      f'                    {tensor_code(layer["weight"])},', f'                    {tensor_code(layer["bias"])}),']
        lines.append("            ),")
    lines += ["        ))", "}", ""]
    args.kotlin.write_text("\n".join(lines))
    print(json.dumps({key: recipe[key] for key in ("sourceBytes", "sourceSha256", "outputBytes", "outputSha256")}))


if __name__ == "__main__":
    main()
